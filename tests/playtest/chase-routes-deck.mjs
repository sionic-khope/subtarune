import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright-core';

const shots = process.env.SHOT_DIR || '/tmp/chase-routes-deck';
fs.mkdirSync(shots, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_EXE, headless: true });
const page = await browser.newPage({ viewport: { width: 1000, height: 780 } });
const checks = [], errors = [];
let fails = 0;
const check = (name, ok, detail) => { checks.push({ name, ok, detail }); if (!ok) fails++; console.log(`${ok ? 'PASS' : 'FAIL'} ${name}`, detail ?? ''); };
page.on('pageerror', error => errors.push(error.message));
const press = key => page.keyboard.press(key, { delay: 65 });
const settled = () => page.waitForFunction(() => !game.dialogue.running && !game.transitioning && game.fade.alpha === 0 && game.entities.every(entity => entity.def.type !== 'door' || entity.cooldown <= 0));
try {
  await page.goto(`${process.env.BASE_URL || 'http://localhost:8000'}/?qa=obj5`);
  await page.waitForFunction(() => !!window.game?.player);
  await press('KeyX');
  await settled();
  await page.evaluate(() => game.changeMap('obj2', 'from_left', true, { enter: false }));
  await settled();
  await page.keyboard.down('ArrowLeft');
  await page.waitForFunction(() => game.textbox.node?.text === '* 형 지금 이럴때가 아니에요.');
  await page.keyboard.up('ArrowLeft');
  await page.waitForFunction(() => game.textbox.state === 'waiting');
  await page.screenshot({ path: path.join(shots, 'left-path-blocked.png') });
  check('left exit blocked with PP dialogue and chase music', await page.evaluate(() => game.mapId === 'obj2' && game.textbox.node.voice === 'ppaman' && game.sound.bgmName === 'baron_intro'));
  await press('KeyC');
  await settled();
  await page.keyboard.down('ArrowLeft');
  await page.waitForTimeout(800);
  await page.keyboard.up('ArrowLeft');
  check('holding the boundary does not spam dialogue', await page.evaluate(() => game.mapId === 'obj2' && !game.dialogue.running));
  await page.evaluate(() => game.changeMap('obj3', 'from_top', true, { enter: false }));
  await settled();
  await page.keyboard.down('ArrowUp');
  await page.waitForFunction(() => game.dialogue.running);
  await page.keyboard.up('ArrowUp');
  check('backtracking to the nest blocked', await page.evaluate(() => game.mapId === 'obj3' && game.textbox.node.text === '* 형 지금 이럴때가 아니에요.'));
  await page.waitForFunction(() => game.textbox.state === 'waiting');
  await press('KeyC');
  await settled();
  await page.keyboard.down('ArrowDown');
  await page.waitForFunction(() => game.mapId === 'obj2');
  await page.keyboard.up('ArrowDown');
  await settled();
  check('forward route still changes map and retains chase music', await page.evaluate(() => game.mapId === 'obj2' && game.sound.bgmName === 'baron_intro'));
  await page.goto(`${process.env.BASE_URL || 'http://localhost:8000'}/?qa=maillard_deck`);
  await page.waitForFunction(() => window.game?.mapId === 'maillard_deck');
  await press('KeyX');
  await settled();
  const before = await page.evaluate(() => ({ x: game.player.x, y: game.player.y, items: game.inventory, party: game.party }));
  await page.screenshot({ path: path.join(shots, 'deck-arrival.png') });
  await page.keyboard.down('ArrowRight');
  await page.waitForTimeout(450);
  await page.keyboard.up('ArrowRight');
  check('deck restores movement and preserves gun and party', await page.evaluate(before => game.player.x > before.x + 50 && game.inventory.filter(item => item === '나무총').length === 1 && game.party.includes('ppaman') && game.party.includes('gyeongsub'), before));
  await page.keyboard.down('ArrowUp');
  await page.waitForTimeout(1100);
  await page.keyboard.up('ArrowUp');
  check('deck ocean boundary is solid', await page.evaluate(() => game.player.y >= 160 && game.player.y < 165));
  await page.screenshot({ path: path.join(shots, 'deck-ocean-edge.png') });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.screenshot({ path: path.join(shots, 'deck-narrow.png') });
  check('no browser runtime errors', errors.length === 0, errors);
} finally {
  fs.writeFileSync(path.join(shots, 'report.json'), JSON.stringify({ checks, errors, fails }, null, 2));
  await browser.close();
}
console.log(`fails=${fails}`);
process.exitCode = fails ? 1 : 0;
